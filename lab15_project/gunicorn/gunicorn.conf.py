# Байланыс адресі мен порт
bind = "127.0.0.1:8000"

# Жұмысшы процестер саны (CPU * 2 + 1 ұсынылады)
workers = 3

# Жұмысшы класы (sync - стандартты, gevent - асинхронды үшін)
worker_class = "sync"

# Лог параметрлері
accesslog = "/var/log/gunicorn/access.log"
errorlog  = "/var/log/gunicorn/error.log"
loglevel  = "info"

# Процесс атауы (ps aux командасында көрінеді)
proc_name = "myproject_gunicorn"

# Таймаут (секунд)
timeout = 120

# Жұмысшыларды автоматты қайта іске қосу (жад ағып кетуінен қорғайды)
max_requests = 1000
max_requests_jitter = 50
